// Builds js/geo-maps.js: simplified world and US map outlines as SVG paths, for the Geography section.
// Setup (once): cd tools && npm i world-atlas@2 us-atlas@3 topojson-client@3 topojson-simplify@3 d3-geo@3 countries-list@3 i18n-iso-countries@7
// Then: node tools/build_geo.js
const path = require("path"), fs = require("fs");
const req = m => require(require.resolve(m, { paths: [__dirname, process.cwd()] }));
const topo = req("topojson-client"), simp = req("topojson-simplify"), d3 = req("d3-geo");
const { countries } = req("countries-list"), iso = req("i18n-iso-countries");
const world = req("world-atlas/countries-110m.json"), us = req("us-atlas/states-albers-10m.json");
// whole map units are plenty at phone size (a unit is under half a screen pixel)
const r1 = s => s.replace(/-?\d+\.\d+/g, n => String(Math.round(+n)));

// ---- world: Natural Earth projection, 960 x 500 ----
const W = 960, H = 500;
const all = topo.feature(world, world.objects.countries);
const proj = d3.geoNaturalEarth1().fitExtent([[4, 4], [W - 4, H - 4]], all), gp = d3.geoPath(proj);
const P = { };   // alpha-2 -> {d, cont, area, c:[x,y]}
const NAMED = { Kosovo: "XK", "N. Cyprus": "CY", Somaliland: "SO" };
for (const f of all.features) {
  const a2 = (f.id && iso.numericToAlpha2(f.id)) || NAMED[f.properties.name];
  if (!a2 || !countries[a2]) continue;
  const prev = P[a2];
  const d = r1(gp(f) || "");
  P[a2] = { d: prev ? prev.d + d : d, cont: countries[a2].continent, area: d3.geoArea(f) + (prev ? prev.area : 0), c: gp.centroid(f).map(v => +v.toFixed(1)), ll: d3.geoCentroid(f).map(v => +v.toFixed(1)) };
}
// continents: merge the countries of each one; Russia is drawn in both Europe and Asia, split at the Urals (60°E)
const contOf = g => { const a2 = (g.id && iso.numericToAlpha2(g.id)) || NAMED[g.properties.name]; return a2 && countries[a2] ? countries[a2].continent : null; };
const CONT = {};
for (const c of ["AF", "AN", "AS", "EU", "NA", "OC", "SA"]) {
  const geoms = world.objects.countries.geometries.filter(g => contOf(g) === c && g.id !== "643");
  CONT[c] = r1(gp(topo.merge(world, geoms)));
}
const urals = +proj([60, 55])[0].toFixed(1);
const pt = (lon, lat) => proj([lon, lat]).map(v => +v.toFixed(1));
const line = coords => r1(gp({ type: "LineString", coordinates: coords }));
const meridian = lon => line(Array.from({ length: 37 }, (_, i) => [lon, -90 + i * 5]));
const parallel = lat => line(Array.from({ length: 73 }, (_, i) => [-180 + i * 5, lat]));
const outline = r1(gp({ type: "Sphere" }));

// ---- US: pre-projected Albers 975 x 610, simplified ----
const ust = simp.presimplify(us);
const usS = simp.simplify(ust, simp.quantile(ust, 0.12));
const up = d3.geoPath();
const STATES = {};
for (const f of topo.feature(usS, usS.objects.states).features) STATES[f.properties.name] = { d: r1(up(f)), c: up.centroid(f).map(v => +v.toFixed(1)), area: up.area(f) };

const out = { world: { w: W, h: H, outline, countries: P, cont: CONT, russia: P.RU && P.RU.d, urals, equator: parallel(0), meridian: meridian(0),
  tropics: [parallel(23.44), parallel(-23.44)], polar: [parallel(66.56), parallel(-66.56)], pt: null },
  us: { w: 975, h: 610, states: STATES } };
// a few points the game needs to place markers (lon, lat -> x, y)
const PTS = { pacificN: [-150, 20], pacificS: [-130, -25], pacificW: [160, 5], atlanticN: [-40, 30], atlanticS: [-15, -25], indian: [80, -20], indianW: [65, -5],
  arctic: [0, 85], arcticW: [-150, 80], southern: [30, -60], southernW: [-100, -62] };
out.world.pt = Object.fromEntries(Object.entries(PTS).map(([k, [lo, la]]) => [k, pt(lo, la)]));
fs.writeFileSync(path.join(__dirname, "..", "js", "geo-maps.js"),
  "// Generated by tools/build_geo.js from Natural Earth (world-atlas) and US Census (us-atlas) outlines. Don't edit by hand.\nwindow.GEOMAPS = " + JSON.stringify(out) + ";\n");
console.log("countries", Object.keys(P).length, "states", Object.keys(STATES).length, "bytes", fs.statSync(path.join(__dirname, "..", "js", "geo-maps.js")).size);
